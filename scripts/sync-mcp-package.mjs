import { promises as fs } from "node:fs";
import path from "node:path";

const root = process.cwd();
const packageRoot = path.join(root, "packages", "unionize-mcp");
const checkOnly = process.argv.includes("--check");
const generatedBanner = "// Generated by scripts/sync-mcp-package.mjs. Edit the canonical source instead.\n";

const sourceMappings = [
  {
    source: "lib/agent/unionize.ts",
    target: "packages/unionize-mcp/src/core.ts",
    replacements: [
      ['from "../content/frontmatterSchema.ts"', 'from "./frontmatterSchema.ts"'],
      ['from "../jurisdictions/usStates.ts"', 'from "./usStates.ts"'],
      ['from "../start/questions.ts"', 'from "./questions.ts"'],
    ],
  },
  {
    source: "lib/jurisdictions/usStates.ts",
    target: "packages/unionize-mcp/src/usStates.ts",
    replacements: [],
  },
  {
    source: "lib/content/contentModel.ts",
    target: "packages/unionize-mcp/src/contentModel.ts",
    replacements: [],
  },
  {
    source: "lib/content/frontmatterSchema.ts",
    target: "packages/unionize-mcp/src/frontmatterSchema.ts",
    replacements: [
      ['from "@/lib/content/contentModel"', 'from "./contentModel.ts"'],
    ],
  },
  {
    source: "lib/start/questions.ts",
    target: "packages/unionize-mcp/src/questions.ts",
    replacements: [],
  },
  {
    source: "scripts/unionize-mcp.ts",
    target: "packages/unionize-mcp/src/server.ts",
    replacements: [
      ['from "../lib/agent/unionize.ts"', 'from "./core.ts"'],
    ],
  },
];

const obsoleteGeneratedFiles = [
  "packages/unionize-mcp/src/content.ts",
  "packages/unionize-mcp/src/pathfinder.ts",
];

const licenseMappings = [
  { source: "LICENSE", target: "packages/unionize-mcp/LICENSE" },
  { source: "CONTENT_LICENSE.md", target: "packages/unionize-mcp/CONTENT_LICENSE.md" },
];

async function expectedSource(mapping) {
  let content = await fs.readFile(path.join(root, mapping.source), "utf8");
  for (const [from, to] of mapping.replacements) {
    if (!content.includes(from)) {
      throw new Error(`Expected import not found in ${mapping.source}: ${from}`);
    }
    content = content.replace(from, to);
  }
  return generatedBanner + content.replace(/\r\n/g, "\n");
}

async function compareOrWrite(relativePath, expected) {
  const absolute = path.join(root, relativePath);
  if (checkOnly) {
    const actual = await fs.readFile(absolute, "utf8").catch(() => "");
    if (actual.replace(/\r\n/g, "\n") !== expected) {
      throw new Error(`${relativePath} is out of sync. Run pnpm sync:mcp-package.`);
    }
    return;
  }

  await fs.mkdir(path.dirname(absolute), { recursive: true });
  await fs.writeFile(absolute, expected, "utf8");
}

for (const mapping of sourceMappings) {
  await compareOrWrite(mapping.target, await expectedSource(mapping));
}

for (const mapping of licenseMappings) {
  const expected = (await fs.readFile(path.join(root, mapping.source), "utf8")).replace(/\r\n/g, "\n");
  await compareOrWrite(mapping.target, expected);
}

const canonicalGuides = path.join(root, "content", "guides");
const packagedGuides = path.join(packageRoot, "content", "guides");
const guideNames = (await fs.readdir(canonicalGuides)).filter((name) => name.endsWith(".mdx")).sort();

if (!checkOnly) {
  await fs.mkdir(packagedGuides, { recursive: true });
}

for (const name of guideNames) {
  const expected = (await fs.readFile(path.join(canonicalGuides, name), "utf8")).replace(/\r\n/g, "\n");
  await compareOrWrite(path.join("packages", "unionize-mcp", "content", "guides", name), expected);
}

const packagedNames = await fs.readdir(packagedGuides).catch(() => []);
const extraGuides = packagedNames.filter((name) => name.endsWith(".mdx") && !guideNames.includes(name));
if (checkOnly && extraGuides.length > 0) {
  throw new Error(`Packaged guide corpus contains obsolete files: ${extraGuides.join(", ")}`);
}
for (const name of extraGuides) {
  await fs.unlink(path.join(packagedGuides, name));
}

for (const relativePath of obsoleteGeneratedFiles) {
  const absolute = path.join(root, relativePath);
  const exists = await fs.access(absolute).then(() => true).catch(() => false);
  if (checkOnly && exists) {
    throw new Error(`${relativePath} is obsolete. Run pnpm sync:mcp-package.`);
  }
  if (!checkOnly && exists) {
    await fs.unlink(absolute);
  }
}

console.log(checkOnly ? "MCP package is synchronized." : "Synchronized MCP package sources and guides.");
